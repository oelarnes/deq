def load_comp_rules() -> str:
    if not COMP_RULES.exists():
        raise FileNotFoundError(
            f"Comprehensive rules not found at {COMP_RULES}. "
            "Run: pdm run python scripts/update_rules.py"
        )
    return COMP_RULES.read_text(encoding="utf-8", errors="replace")


def find_rule_by_name(rules_text: str, keyword: str, max_lines: int = 12) -> str:
    """Find a keyword's rule section by searching for its name in the numbered rules.

    Looks for lines like '702.191. Increment' and extracts the section text.
    Falls back to the glossary if no numbered section is found.
    """
    lines = rules_text.splitlines()

    # Match section headings: "702.191. KeywordName" or "722. KeywordName"
    heading_re = re.compile(
        r"^(\d+(?:\.\d+)*)\.\s+" + re.escape(keyword) + r"\b",
        re.IGNORECASE,
    )

    start = -1
    cur_section_parts: list[int] = []
    for i, line in enumerate(lines):
        m = heading_re.match(line.strip())
        if m:
            start = i
            cur_section_parts = [int(p) for p in m.group(1).split(".")]
            break

    if start < 0:
        return _find_glossary_entry(rules_text, keyword)

    result = [lines[start].strip()]

    for i in range(start + 1, len(lines)):
        line = lines[i].strip()
        if not line:
            continue

        # Stop when we hit a new section at the same or higher level
        next_heading = re.match(r"^(\d+(?:\.\d+)*)\.", line)
        if next_heading:
            next_parts = [int(p) for p in next_heading.group(1).split(".")]
            # Compare at the level of the current section
            depth = len(cur_section_parts)
            next_at_depth = next_parts[:depth]
            cur_at_depth = cur_section_parts[:depth]
            if len(next_at_depth) == depth and next_at_depth > cur_at_depth:
                # Check it's not a deeper sub-section (702.191a format)
                # Those have letters after the number, not parsed here
                if not re.match(r"^\d+(?:\.\d+)*[a-z]", line):
                    break

        result.append(line)
        if len(result) >= max_lines:
            break

    return "\n".join(result)


def _find_glossary_entry(rules_text: str, term: str) -> str:
    """Find a term in the glossary section (fallback for find_rule_by_name)."""
    lines = rules_text.splitlines()
    in_glossary = False
    collecting = False
    result = []

    for line in lines:
        stripped = line.strip()
        if "Glossary" in stripped and not in_glossary and not collecting:
            in_glossary = True
            continue
        if not in_glossary:
            continue
        if not collecting:
            if stripped.lower() == term.lower():
                collecting = True
                result.append(stripped)
        else:
            if not stripped:
                break
            if len(stripped) < 60 and "." not in stripped and stripped[0].isupper():
                break
            result.append(stripped)
            if len(result) >= 5:
                break

    return "\n".join(result)


def detect_layouts(rows: list[dict]) -> set[str]:
    """Detect multi-face layouts from inline markers in oracle_text."""
    layouts: set[str] = set()
    for row in rows:
        oracle = (row.get("oracle_text") or "").lower()
        if "prepare spell —" in oracle or "enters prepared" in oracle:
            layouts.add("prepare")
        if "adventure:" in oracle:
            layouts.add("adventure")
        if "transforms into:" in oracle:
            layouts.add("transform")
        if "back face —" in oracle:
            layouts.add("modal_dfc")
    return layouts


def detect_keywords(oracle_all: str) -> tuple[list[str], list[str]]:
    """Return (novel_keywords, evergreen_keywords) detected in oracle text."""
    novel: list[str] = []
    evergreen: list[str] = []
    seen = set(KNOWN_ABILITY_WORDS)  # don't double-count ability words

    # Scan for keywords. Order matters: check multi-word first.
    all_keywords = sorted(
        set(EVERGREEN_KEYWORDS) | {kw for kw in _extra_keywords()},
        key=lambda k: -len(k),
    )

    for kw in all_keywords:
        if kw in seen:
            continue
        if re.search(r"\b" + re.escape(kw) + r"\b", oracle_all, re.IGNORECASE):
            seen.add(kw)
            if kw in EVERGREEN_KEYWORDS:
                evergreen.append(kw)
            else:
                novel.append(kw)

    return sorted(novel), sorted(evergreen)


def _extra_keywords() -> list[str]:
    """Additional known keywords not in EVERGREEN_KEYWORDS (newer/set-specific)."""
