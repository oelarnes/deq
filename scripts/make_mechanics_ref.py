def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--set", required=True, dest="set_code", metavar="SET")
    args = parser.parse_args()

    SET = args.set_code
    cards_path = SET_REVIEWS / f"{SET}_cards.csv"
    if not cards_path.exists():
        print(f"ERROR: Card CSV not found: {cards_path}", file=sys.stderr)
        print("Run: pdm run python scripts/make_card_csv.py --set " + SET, file=sys.stderr)
        sys.exit(1)

    try:
        rules = load_comp_rules()
    except FileNotFoundError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)

    with open(cards_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    full_oracle = " ".join((r.get("oracle_text") or "").lower() for r in rows)

    # Detect ability words
    ability_words_present = sorted(
        aw for aw in KNOWN_ABILITY_WORDS
        if re.search(r"\b" + re.escape(aw) + r"\b", full_oracle)
    )

    # Detect keywords
    novel_keywords, evergreen_kws = detect_keywords(full_oracle)

    # Detect multi-face layouts from inline markers
    layouts_present = detect_layouts(rows)

    # Build output
    out_lines = [f"# {SET} Mechanics Reference", ""]
    wrote_any = False

    # --- Multi-face cards ---
    if layouts_present:
        wrote_any = True
        out_lines.append("## Multi-Face Cards")
        out_lines.append(
            "Back-face oracle text is embedded inline in the card CSV, separated by ' || '."
            " The agent does not need to look up prepare spells, adventures, or back faces separately."
        )
        out_lines.append("")

        for layout in sorted(layouts_present):
            title = LAYOUT_TITLES.get(layout, layout.title())
            rule_section = LAYOUT_RULES.get(layout)
            heading = f"{title} (rule {rule_section})" if rule_section else title
            out_lines.append(f"### {heading}")

            desc = LAYOUT_DESCRIPTIONS.get(layout)
            if desc:
                out_lines.append(desc)
            out_lines.append("")

    # --- Novel keyword abilities ---
    if novel_keywords:
        wrote_any = True
        out_lines.append("## New or Set-Specific Keyword Abilities")
        out_lines.append("")

        for kw in novel_keywords:
            out_lines.append(f"### {kw.title()}")
            rule_text = find_rule_by_name(rules, kw.title())
            if not rule_text:
                rule_text = find_rule_by_name(rules, kw)
            if rule_text:
                out_lines.append(rule_text)
            else:
                out_lines.append("(No rule entry found — refer to card text.)")
            out_lines.append("")

    # --- Ability words ---
    if ability_words_present:
        wrote_any = True
        out_lines.append("## Ability Words")
        out_lines.append(
            "The following are ability words (rule 207.2c). They have no separate"
            " comprehensive rules entry — each card's oracle text fully defines the"
            " trigger condition and effect for that card. Read each card carefully;"
            " do not generalize the trigger condition across cards with the same word."
        )
        out_lines.append("")
        for aw in ability_words_present:
            out_lines.append(f"- **{aw.title()}**")
        out_lines.append("")
        out_lines.append(
            "Ability words are purely cosmetic labels — they mark a theme, but the"
            " actual rules are on the card."
        )
        out_lines.append("")

    # --- Common keywords footer ---
    if evergreen_kws:
        out_lines.append("## Common Keywords (no rules excerpt needed)")
        out_lines.append(
            "These keywords appear in the set but are well-known. Agents are assumed"
            " to understand them without additional rules text:"
        )
        out_lines.append("")
        out_lines.append(", ".join(kw.title() for kw in evergreen_kws) + ".")
        out_lines.append("")

    if not wrote_any:
        out_lines.append("(No set-specific mechanics detected.)")

    out_path = SET_REVIEWS / f"{SET}_mechanics.txt"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(out_lines))

    print(f"Wrote mechanics reference → {out_path}")
    if layouts_present:
        print(f"  Multi-face layouts: {', '.join(sorted(layouts_present))}")
    if novel_keywords:
        print(f"  Novel keywords (with rule excerpts): {', '.join(novel_keywords)}")
    if ability_words_present:
        print(f"  Ability words: {', '.join(ability_words_present)}")
    if evergreen_kws:
        print(f"  Common keywords (no excerpts): {', '.join(evergreen_kws)}")


if __name__ == "__main__":
    main()
